const en: Record<MessageKey, string> = { ...baseEn, ...adminEn };
export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { ar, en };

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  let s: string = MESSAGES[locale][key] ?? MESSAGES.ar[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
